// Trunk post_build hook (see Trunk.toml) — issue #995.
//
// The world editor's script mode (host-fn autocomplete + Rhai diagnostics)
// loads the real phoenix wasm-bindgen module through `editor/script-wasm.js`,
// whose `DEFAULT_MODULE_URL` is the STABLE `../dist/phoenix.js`. But
// `trunk build` emits a CONTENT-HASHED glue (`project-phoenix-<hash>.js` +
// `_bg.wasm`) whose name changes every build, so the editor cannot import it
// under a fixed name. This hook writes a tiny stable `phoenix.js` alias next to
// the hashed glue that re-exports it — so the editor's import survives
// content-hash churn without an importmap or a copy of the 50 MB wasm.
//
// Runs on BOTH dev and release builds (unlike `wasm-opt-fixup`, which is
// release-only): the editor needs the alias whatever the build profile.
//
// Decision (issue #995 Q1 — slim vs. full WASM): the alias re-exports the FULL
// game glue as-is rather than building a dedicated slim target. That glue IS
// the authoritative host — `wasm_get_script_host_fns` / `wasm_script_diagnostics`
// are defined against the real loading engine, so enumerating signatures and
// compiling a Rhai snippet against it is by design. `script-wasm.js` loads it
// LAZILY (only when a script unit is opened), so the ~50 MB wasm never touches
// the editor's base page load. A slim `wasm-bindgen` target exposing only the
// two exports would cut that download dramatically and is a reasonable future
// optimisation, but is out of scope here.

import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Pick the most recently written phoenix wasm-bindgen glue in `distDir`.
 *
 * Matches `project-phoenix-<hash>.js` (and a hypothetical un-hashed
 * `project-phoenix.js`) but never the `phoenix.js` alias this script writes.
 * Stale hashes from earlier builds are not cleaned up in the staging dir, so
 * pick the newest by mtime rather than an arbitrary directory-order match —
 * the same tie-break `wasm-opt-fixup.mjs` uses for `*_bg.wasm`.
 *
 * @param {string} distDir
 * @param {typeof readdirSync} [readdir]  Injectable for tests.
 * @param {typeof statSync} [stat]        Injectable for tests.
 * @returns {string | undefined} the glue filename, or undefined if none found.
 */
export function findHashedGlue(distDir, readdir = readdirSync, stat = statSync) {
  return readdir(distDir)
    .filter((f) => /^project-phoenix.*\.js$/.test(f) && f !== "phoenix.js")
    .map((f) => ({ f, mtime: stat(join(distDir, f)).mtimeMs }))
    .sort((a, b) => b.mtime - a.mtime)[0]?.f;
}

/**
 * Build the source of the stable `dist/phoenix.js` editor alias for a given
 * hashed glue filename.
 *
 * `export *` re-exports the glue's NAMED exports (`wasm_get_script_host_fns`,
 * `wasm_script_diagnostics`, `initSync`, …) but NOT its default (`init`), so the
 * default is re-exported explicitly — AND bound to the hashed `_bg.wasm` path,
 * because wasm-bindgen's argument-less `init()` otherwise fetches the UN-hashed
 * `project-phoenix_bg.wasm` (resolved against the glue's own URL), which trunk
 * never emits. Binding the path here keeps `script-wasm.js`'s plain
 * `mod.default()` call correct without it having to know the content hash.
 *
 * @param {string} hashedJs  e.g. `project-phoenix-9b074c85c4a6a2d7.js`
 * @returns {string} module source for `phoenix.js`
 */
export function aliasSource(hashedJs) {
  const hashedWasm = hashedJs.replace(/\.js$/, "_bg.wasm");
  return `// AUTO-GENERATED by scripts/wasm-editor-alias.mjs (Trunk post_build, issue #995).
// Stable editor entry re-exporting the content-hashed wasm-bindgen glue.
// Do not edit by hand; regenerated on every build.
import init from './${hashedJs}';

// Named exports: wasm_get_script_host_fns, wasm_script_diagnostics, initSync, …
export * from './${hashedJs}';

// wasm-bindgen's default init() fetches the UN-hashed _bg.wasm relative to the
// glue's URL; bind the hashed path so the editor's argument-less mod.default()
// finds the file trunk actually emitted.
const WASM_URL = new URL('./${hashedWasm}', import.meta.url);

export default function initPhoenixEditor(opts) {
  return init(opts ?? { module_or_path: WASM_URL });
}
`;
}

/**
 * Discover the hashed glue in `distDir` and write the stable `phoenix.js` alias
 * beside it. Throws if no glue is present (a genuine build failure).
 *
 * @param {string} distDir
 * @returns {{ hashedJs: string, outPath: string }}
 */
export function writeAlias(distDir) {
  const hashedJs = findHashedGlue(distDir);
  if (!hashedJs) {
    throw new Error(
      `wasm-editor-alias: no project-phoenix-<hash>.js found in ${distDir}`,
    );
  }
  const outPath = join(distDir, "phoenix.js");
  writeFileSync(outPath, aliasSource(hashedJs));
  return { hashedJs, outPath };
}

// Run only when invoked directly as the Trunk hook — NOT when imported by tests.
// (import.meta.main is not available on the Node used here, so sniff argv[1].)
const invokedDirectly =
  typeof process !== "undefined" &&
  process.argv[1] &&
  process.argv[1].replace(/\\/g, "/").endsWith("scripts/wasm-editor-alias.mjs");

if (invokedDirectly) {
  const distDir = process.argv[2] ?? "dist";
  try {
    const { hashedJs, outPath } = writeAlias(distDir);
    console.log(`wasm-editor-alias: ${outPath} -> ${hashedJs}`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
