// #1044: retain every mission-owned string for the human editorial pass.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseCsv } from '../gui/strings.js';
import { rowLineNumbers } from './strings-csv.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const csv = readFileSync(path.join(root, 'assets/strings/strings.csv'), 'utf8');
const world = readFileSync(path.join(root, 'assets/worlds/falling_skyway.toml'), 'utf8');
const [header, ...data] = parseCsv(csv);
const lines = rowLineNumbers(csv, [header, ...data]);
const rows = data.map((fields, index) => ({
  ...Object.fromEntries(header.map((key, column) => [key, fields[column] ?? ''])),
  line: lines[index + 1],
})).filter(row => row.id.startsWith('world.falling_skyway.'));
if (!rows.length || rows.some(row => !row.line) || new Set(rows.map(row => row.id)).size !== rows.length) {
  throw new Error('Mission copy inventory must be nonempty with unique IDs');
}
const groups = new Map([
  ['Briefing and contact labels', []], ['Objectives and work orders', []],
  ['Dossier, evidence and commitments', []], ['Dialogue and transmissions', []],
  ['Warnings, deadlines and operational status', []], ['Endings and debrief reports', []],
]);
function group(id) {
  const tail = id.slice('world.falling_skyway.'.length);
  if (/^(game_over|report)\.|^comms\.debrief/.test(tail)) return 'Endings and debrief reports';
  if (/^(objective|civilian_order)\./.test(tail)) return 'Objectives and work orders';
  if (/^(evidence|commitment)\./.test(tail)) return 'Dossier, evidence and commitments';
  if (/^comms\./.test(tail)) return 'Dialogue and transmissions';
  if (/^(global|entity|available_ships|workforce)\./.test(tail)) return 'Briefing and contact labels';
  return 'Warnings, deadlines and operational status';
}
for (const row of rows) groups.get(group(row.id)).push(row);
const bracketed = rows.filter(row => /^\[[\s\S]*\]$/.test(row.en)).length;
const out = [
  '# Falling Skyway copy approval inventory (#1044)', '',
  'Generated by `node scripts/skyway-copy-inventory.mjs`; verify with `--check`.', '',
  `**${rows.length} mission-owned strings; ${bracketed} fully bracketed. Human approval: NOT RUN.**`, '',
  'This includes every `world.falling_skyway.*` CSV row, including rows retained',
  'for alternate branches and reports. Brackets and wording are reproduced unchanged.',
  'Generic console controls, shared hull tutorials and engine messages remain in',
  'the shared string table; this is the complete mission-copy inventory, not a',
  'claim to inventory every generic control visible while playing.', '',
  `World SHA-256: \`${createHash('sha256').update(world).digest('hex')}\`.`,
  `String-table SHA-256: \`${createHash('sha256').update(csv).digest('hex')}\`.`, '',
];
for (const [name, entries] of groups) {
  out.push(`## ${name} (${entries.length})`, '');
  for (const row of entries) {
    out.push(`### ${row.id}`, '', row.en, '',
      `Source: [strings.csv:${row.line}](../../assets/strings/strings.csv#L${row.line}).`,
      `Context: ${row.context}`, '',
      `Bracketed: ${/^\[[\s\S]*\]$/.test(row.en) ? 'yes' : 'no'}. Editorial decision: pending.`, '');
  }
}
const rendered = out.join('\n');
const destination = path.join(root, 'docs/acceptance/1044-skyway-copy-inventory.md');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== rendered) throw new Error('Skyway copy inventory is stale');
} else writeFileSync(destination, rendered);
console.log(`${rows.length} mission strings, ${bracketed} bracketed; inventory ${process.argv.includes('--check') ? 'current' : 'written'}`);
