// Match the reviewed model to the *rendered* original, then declare its ladder.
// Run before generate-lods.mjs and capture-billboards.mjs, from the repo root.
import {readFile,writeFile} from 'node:fs/promises';
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {getBounds} from '@gltf-transform/functions';
import {parse,stringify} from 'smol-toml';
import assert from 'node:assert/strict';
import {migrateMarkers} from './destroyer-markers.mjs';
const original='assets/models/alliance_destroyer';
const candidate='assets/models/alliance_destroyer_recreated';
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS);
const reference=parse(await readFile(`${original}.model.toml`,'utf8'));
assert.equal(reference.base.rotation[0],0);
assert.equal(reference.base.rotation[2],0);
const rotation=[0,Math.sin(reference.base.rotation[1]/2),0,Math.cos(reference.base.rotation[1]/2)];
function rig(doc,base){
  const scene=doc.getRoot().listScenes()[0];
  const parent=doc.createNode('Measured base rig');
  for(const child of [...scene.listChildren()])parent.addChild(child);
  scene.addChild(parent);
  parent.setTranslation(base.offset).setScale(base.scale).setRotation(rotation);
  return {scene,parent};
}
const size=b=>b.max.map((v,i)=>v-b.min[i]);
const centre=b=>b.max.map((v,i)=>(v+b.min[i])/2);
const old=rig(await io.read(`${original}.glb`),reference.base);
const target=getBounds(old.scene),targetSize=size(target),targetCentre=centre(target);
// Always start from the unscaled art master, making repeated preparation safe.
const doc=await io.read('raw/models/PPAllianceDestroyer/recreated/alliance_destroyer_recreated.glb');
const raw=getBounds(doc.getRoot().listScenes()[0]);
let base={offset:[0,0,0],rotation:reference.base.rotation,scale:size(raw).map((v,i)=>targetSize[i]/v)};
const current=rig(doc,base);
// Measure the actual transformed vertices. Iteration accounts for the original
// rig's almost-180-degree yaw without copying its stale advisory extents.
for(let pass=0;pass<12;pass++){
  const bounds=getBounds(current.scene),actual=size(bounds);
  base.scale=base.scale.map((s,i)=>s*targetSize[i]/actual[i]);
  current.parent.setScale(base.scale);
  const c=centre(getBounds(current.scene));
  base.offset=base.offset.map((v,i)=>v+targetCentre[i]-c[i]);
  current.parent.setTranslation(base.offset);
}
const bounds=getBounds(current.scene);
assert.ok(size(bounds).every((v,i)=>Math.abs(v-targetSize[i])<1e-6));
assert.ok(centre(bounds).every((v,i)=>Math.abs(v-targetCentre[i])<1e-6));
// Keep this correction INSIDE the GLB scene graph. Both generated tiers and
// LOD0 then carry exactly the same basis even in viewers which apply only a
// scale, rather than the primary rig's rotation, to identity-rig LOD tiers.
await io.write(`${candidate}.glb`,doc);
const identity={offset:[0,0,0],rotation:[0,0,0],scale:[1,1,1]};
const lod=reference.lod.map(level=>{
  const copy=structuredClone(level);
  for(const key of ['model','billboard'])if(copy[key])copy[key]=copy[key].replace(original,candidate);
  if(copy.generate){
    copy.generate.source=copy.generate.source.replace(original,candidate);
    // Dense hard-surface UV seams prevent useful direct simplification. The
    // standard optional remesh is only for distant tiers; keep LOD0 untouched.
    copy.generate.remesh_voxel_size=.065;
    const middle=copy.max_distance===100;
    copy.generate.ratio=middle ? .10 : .025;
    copy.generate.error=middle ? .01 : .02;
  }
  if(copy.capture)copy.capture.source=copy.capture.source.replace(original,candidate);
  return copy;
});
await writeFile(`${candidate}.model.toml`,
  '# Rebuilt destroyer: dimensions and centre matched to the original rendered GLB.\n'+
  '# Generated by scripts/art/prepare-destroyer-lods.mjs; capture refreshes billboard scale.\n'+
  '# Gameplay markers preserve the original rig attachment positions and directions.\n'+
  stringify({base:identity,extents:{...bounds,size:size(bounds)},markers:migrateMarkers(reference),lod}));
const report={reference:`${original}.glb`,candidate:`${candidate}.glb`,referenceRenderedBounds:target,candidateRenderedBounds:bounds,referenceCachedExtents:reference.extents,base,dimensions:size(bounds)};
await writeFile('raw/models/PPAllianceDestroyer/recreated/size-match.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
