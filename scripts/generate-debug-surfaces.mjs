// Deterministic Rust -> JavaScript Debug Surface catalogue generator (#1267).
//
// `src/core/debug_surface.rs` is the only authored identity/order/wire-name
// table. The pure-JS phone cannot import Rust and server.html's classic script
// cannot import an ESM binding directly, so this script derives one committed
// module from the macro invocation. The module exports symbols for ESM callers
// and publishes the same frozen values on `globalThis.phDebugSurfaces` for the
// classic host script.
//
// Run:
//   npm run debug-surfaces          # regenerate the committed module
//   npm run debug-surfaces:check    # fail when the module has drifted

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const DEBUG_SURFACE_RUST_PATH = 'src/core/debug_surface.rs';
export const DEBUG_SURFACE_JS_PATH = 'gui/debug-surfaces.generated.js';

/**
 * Parse the one `define_debug_surface_catalogue! { ... }` invocation.
 *
 * This deliberately accepts only the narrow row syntax the macro is authored
 * with. A future syntax change must update the generator rather than silently
 * dropping a catalogue row.
 *
 * @param {string} source
 * @returns {Array<{variant: string, wireName: string}>}
 */
export function parseDebugSurfaceCatalogue(source) {
  const invocation = source.match(
    /(?:^|\n)define_debug_surface_catalogue!\s*\{([\s\S]*?)\n\}/,
  );
  if (!invocation) {
    throw new Error('Debug Surface macro invocation was not found');
  }

  const rows = [];
  for (const [offset, rawLine] of invocation[1].split(/\r?\n/).entries()) {
    const line = rawLine.trim();
    if (!line || line.startsWith('///') || line.startsWith('#[')) continue;

    const row = line.match(
      /^([A-Za-z][A-Za-z0-9_]*)\s*=>\s*"([A-Za-z][A-Za-z0-9_]*)"\s*,$/,
    );
    if (!row) {
      throw new Error(`Unrecognised Debug Surface row at invocation line ${offset + 1}: ${line}`);
    }
    rows.push({ variant: row[1], wireName: row[2] });
  }

  if (rows.length === 0) throw new Error('Debug Surface catalogue is empty');

  const variants = new Set(rows.map((row) => row.variant));
  const wireNames = new Set(rows.map((row) => row.wireName));
  if (variants.size !== rows.length) throw new Error('Debug Surface variants must be unique');
  if (wireNames.size !== rows.length) throw new Error('Debug Surface wire names must be unique');

  return rows;
}

/** Render the committed ESM/global artefact byte-for-byte. */
export function renderDebugSurfaceModule(rows) {
  const symbols = rows
    .map((row) => `  ${row.variant}: ${JSON.stringify(row.wireName)},`)
    .join('\n');
  const order = rows
    .map((row) => `  DEBUG_SURFACE.${row.variant},`)
    .join('\n');

  return `// AUTO-GENERATED by scripts/generate-debug-surfaces.mjs from
// src/core/debug_surface.rs. Do not edit this file by hand.
//
// Rust owns Debug Surface identity, stable order, and wire names. ESM modules
// import these symbols; server.html reads the same frozen values through the
// phDebugSurfaces global published at the bottom.

export const DEBUG_SURFACE = Object.freeze({
${symbols}
});

export const DEBUG_SURFACE_ORDER = Object.freeze([
${order}
]);

export const DEBUG_SURFACE_GLOBAL = Object.freeze({
  DebugSurface: DEBUG_SURFACE,
  order: DEBUG_SURFACE_ORDER,
});

if (typeof globalThis !== 'undefined') {
  globalThis.phDebugSurfaces = DEBUG_SURFACE_GLOBAL;
}
`;
}

/** Derive the expected module from the authoritative Rust source. */
export async function expectedDebugSurfaceModule(repoRoot = root) {
  const rust = await readFile(path.join(repoRoot, DEBUG_SURFACE_RUST_PATH), 'utf8');
  return renderDebugSurfaceModule(parseDebugSurfaceCatalogue(rust));
}

/** Fail without writing when the committed generated module is stale. */
export async function assertDebugSurfaceModuleCurrent(repoRoot = root) {
  const expected = await expectedDebugSurfaceModule(repoRoot);
  let actual;
  try {
    actual = await readFile(path.join(repoRoot, DEBUG_SURFACE_JS_PATH), 'utf8');
  } catch (error) {
    if (error && error.code === 'ENOENT') actual = '';
    else throw error;
  }
  if (actual !== expected) {
    throw new Error(
      `${DEBUG_SURFACE_JS_PATH} is stale; run \`npm run debug-surfaces\` and commit the result`,
    );
  }
}

/** Regenerate the committed module. */
export async function writeDebugSurfaceModule(repoRoot = root) {
  const expected = await expectedDebugSurfaceModule(repoRoot);
  await writeFile(path.join(repoRoot, DEBUG_SURFACE_JS_PATH), expected, 'utf8');
}

const invokedDirectly =
  typeof process !== 'undefined' &&
  process.argv[1] &&
  process.argv[1].replace(/\\/g, '/').endsWith('scripts/generate-debug-surfaces.mjs');

if (invokedDirectly) {
  const args = process.argv.slice(2);
  const check = args.length === 1 && args[0] === '--check';
  if (args.length > (check ? 1 : 0)) {
    console.error('usage: node scripts/generate-debug-surfaces.mjs [--check]');
    process.exit(2);
  }
  try {
    if (check) {
      await assertDebugSurfaceModuleCurrent(root);
      console.log(`debug-surfaces: ${DEBUG_SURFACE_JS_PATH} is current`);
    } else {
      await writeDebugSurfaceModule(root);
      console.log(`debug-surfaces: regenerated ${DEBUG_SURFACE_JS_PATH}`);
    }
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
